const express = require('express');
const { requireAuth, requireRole } = require('../middleware/authMiddleware');
const c = require('../controllers/physiotherapistPortalController');
const router = express.Router();
router.use(requireAuth, requireRole('physiotherapist'));
router.get('/overview', c.getOverview);
router.get('/patients', c.listPatients);
router.get('/appointments', c.listAppointments);
router.post('/appointments', c.createAppointment);
router.patch('/appointments/:id', c.updateAppointment);
router.get('/recovery-plans', c.listPlans);
router.post('/recovery-plans', c.createPlan);
router.patch('/recovery-plans/:id', c.updatePlan);
router.delete('/recovery-plans/:id', c.deletePlan);
router.get('/exercises', c.listExercises);
router.post('/exercises', c.createExercise);
router.delete('/exercises/:id', c.deleteExercise);
router.get('/messages', c.listMessages);
router.post('/messages', c.sendMessage);
router.patch('/messages/read', c.markMessagesRead);
router.patch('/messages/:patientId/read', c.markMessagesRead);
router.get('/profile', c.getProfile);
module.exports = router;
